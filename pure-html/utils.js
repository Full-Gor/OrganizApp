function getRushColorStyle(colorValue) {
  const color = RushStorage.RUSH_COLORS.find(c => c.value === colorValue);
  if (!color) return { bg: '#f97316', text: '#ffffff', border: '#f97316' };
  return { bg: color.bg, text: color.text, border: color.border };
}

